def get_skill_input(char_id, card_id):
    for (cid, cid2), slot_idx in SKILL_SLOT.items():
        if cid == char_id and cid2 == card_id:
            inputs = CHAR_SKILL_INPUTS.get(char_id, [])
            if slot_idx < len(inputs):
                return inputs[slot_idx]
    return "?"


def get_card_name(char_id, card_id):
    if card_id <= 20:
        return SYSTEM_CARDS.get(card_id, f"Unknown System Card {card_id}")
    if 100 <= card_id <= 114:
        return CHAR_SKILL_CARDS.get(char_id, {}).get(card_id, f"Unknown Skill Card {card_id}")
    if 200 <= card_id <= 219:
        return CHAR_SPELL_CARDS.get(char_id, {}).get(card_id, f"Unknown Spell Card {card_id}")
    return f"Unknown Card {card_id}"
